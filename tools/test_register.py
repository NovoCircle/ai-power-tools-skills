"""The skills test register (TEST-REGISTER.md), checked.

Run:  python -m pytest tools/test_register.py

TEST-REGISTER.md is generated by tools/register.py from the product itself: the skills folder,
the shipped-file manifest, and the hand rows in tools/register.toml. These checks keep it honest:

* the committed file equals a fresh generation (otherwise: `python tools/register.py --write`);
* every exemption has a reason and names a unit and kind that exist;
* every COVERS entry and every acceptance case's Covers line names something that exists;
* no gap outside the known-gap list, and no closed gap left in it (the ratchet);
* the known-gap list is empty: xfail(strict=True) until the gaps are closed.

The generator reads files and the syntax tree; no skill module is imported. This file is not
shipped: it lives in ``tools/``, which ``manifest.json`` does not list.
"""
from __future__ import annotations

# Backlog items this module pins.
PINS = ("APT-2026-0505",)

import copy
import importlib.util
import json
import sys
from pathlib import Path

import pytest

_PATH = Path(__file__).resolve().parent / "register.py"
_spec = importlib.util.spec_from_file_location("register_under_test", _PATH)
register = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = register      # dataclasses look their module up here
_spec.loader.exec_module(register)

ROOT = register.ROOT
CONFIG = register.load_config()
MODEL = register.build(ROOT, CONFIG)
GAPS = set(MODEL.gaps())
KNOWN = set(register.known_gaps(CONFIG))


def _by_kind(group):
    return [u for u in MODEL.units if u.group == group]


def test_the_register_finds_the_units_it_should():
    # An enumeration that finds nothing would make every check below pass vacuously.
    assert len(_by_kind("skill")) >= 24, [u.id for u in _by_kind("skill")]
    assert len(_by_kind("prog")) >= 18, [u.id for u in _by_kind("prog")]
    assert len(_by_kind("asset")) >= 12, [u.id for u in _by_kind("asset")]
    assert {u.id for u in _by_kind("srf")} == {"srf:plugin"}


def test_the_committed_register_equals_a_fresh_generation():
    committed = register.REGISTER_PATH.read_bytes()
    assert committed == register.render(MODEL).encode("utf-8"), (
        "TEST-REGISTER.md is stale: run `python tools/register.py --write` and commit it")


def test_the_register_has_lf_line_endings_and_posix_paths():
    committed = register.REGISTER_PATH.read_bytes()
    assert b"\r" not in committed
    assert b"\\" not in committed.replace(b"\\|", b""), "a backslash path leaked into the register"


def test_the_register_and_its_tooling_do_not_ship():
    manifest = json.loads((ROOT / "manifest.json").read_text(encoding="utf-8"))
    shipped = {f for skill in manifest["skills"] for f in skill["files"]}
    names = {Path(f).name for f in shipped}
    assert not names & {"TEST-REGISTER.md", "register.py", "register.toml", "test_register.py"}
    assert not [f for f in shipped if f.startswith("tools/")]


def test_there_are_no_structural_problems():
    # Stale exemptions, a COVERS entry naming no unit, a Covers line naming no heading,
    # a hand row naming a test or CI step that does not exist.
    assert MODEL.problems == []


def test_no_gap_outside_the_known_list():
    new = sorted(GAPS - KNOWN)
    assert not new, (
        f"{len(new)} gap(s) not in tools/register.toml known_gaps. Add the missing test, or write "
        f"an exemption with a reason: {new}")


def test_no_closed_gap_is_left_in_the_known_list():
    closed = sorted(KNOWN - GAPS)
    assert not closed, (
        f"{len(closed)} known gap(s) are closed or name no unit; remove them from "
        f"tools/register.toml known_gaps: {closed}")


@pytest.mark.xfail(strict=True, reason=(
    f"{len(KNOWN)} known gaps: "
    f"{sum(1 for _, k in sorted(KNOWN) if k == 'A')} skills without A, "
    f"{sum(1 for u, k in sorted(KNOWN) if k == 'U' and u.startswith('asset:'))} data assets without U, "
    f"{sum(1 for u, k in sorted(KNOWN) if k == 'D')} surface without D"))
def test_the_known_gap_list_is_empty():
    assert not KNOWN


# --- the checks above must be able to fail ---------------------------------------------------
# A check that cannot fail is worth nothing, so each rule is also fed something known-bad.

def _problems_with(**changes):
    config = copy.deepcopy(CONFIG)
    config.update(changes)
    return register.build(ROOT, config).problems


def test_an_exemption_without_a_reason_is_a_problem():
    bad = [{"unit": "prog:_shared/tools/tmdl.py", "kind": "U", "reason": " "}]
    assert any("no reason" in p for p in _problems_with(exemption=bad))


def test_an_exemption_naming_a_missing_unit_or_kind_is_a_problem():
    problems = _problems_with(exemption=[
        {"unit": "skill:no-such-skill", "kind": "A", "reason": "x"},
        {"unit": "prog:_shared/tools/tmdl.py", "kind": "L", "reason": "x"},
    ])
    assert any("unit that does not exist" in p for p in problems)
    assert any("does not require" in p for p in problems)


def _demo_skills(root, cases):
    """Skills under a throwaway root: {name: number of covered cases, or None for no case file}."""
    for name, n in cases.items():
        skill = root / "plugins" / "ai-power-tools" / "skills" / name
        skill.mkdir(parents=True)
        (skill / "SKILL.md").write_text("# Demo\n\n## Real heading\n", encoding="utf-8")
        if n is not None:
            (skill / "references").mkdir()
            (skill / "references" / "test-cases.md").write_text(
                "".join(f"### TC-{i:02d} - case\n\nCovers: Real heading\n\n" for i in range(1, n + 1)),
                encoding="utf-8")
    (root / "manifest.json").write_text(json.dumps({"skills": []}), encoding="utf-8")


def test_a_valid_exemption_closes_the_gap_it_names(tmp_path):
    _demo_skills(tmp_path, {"demo": None})
    unit = "skill:demo"
    config = {"hand_row": [], "exemption": [{"unit": unit, "kind": "A", "reason": "illustration"}]}
    model = register.build(tmp_path, config)
    assert model.problems == []
    assert (unit, "A") not in model.gaps()
    assert model.unit(unit).cells["A"].state == "exempt"


def test_a_hand_row_naming_a_missing_test_is_a_problem():
    config = copy.deepcopy(CONFIG)
    config["hand_row"][0]["u_tests"] = ["tools/test_no_such_module.py"]
    config["hand_row"][0]["u_ci_steps"] = ["No such step"]
    problems = register.build(ROOT, config).problems
    assert any("not a test module" in p for p in problems)
    assert any("not a step" in p for p in problems)


def test_a_covers_line_must_name_a_real_heading(tmp_path):
    skill = tmp_path / "plugins" / "ai-power-tools" / "skills" / "demo"
    (skill / "references").mkdir(parents=True)
    (skill / "SKILL.md").write_text("# Demo\n\n## Real heading\n", encoding="utf-8")
    (skill / "references" / "test-cases.md").write_text(
        "### TC-01 - one\n\nCovers: Real heading\n\n### TC-02 - two\n\nCovers: Invented heading\n",
        encoding="utf-8")
    (tmp_path / "manifest.json").write_text(json.dumps({"skills": []}), encoding="utf-8")
    config = {"hand_row": []}
    model = register.build(tmp_path, config)
    assert model.unit("skill:demo").cells["A"].state == "present"
    assert model.unit("skill:demo").cells["A"].ids == [
        "plugins/ai-power-tools/skills/demo/references/test-cases.md#TC-01"]
    assert len(model.problems) == 1 and "Invented heading" in model.problems[0]


def test_a_case_file_with_no_covers_line_is_a_gap(tmp_path):
    skill = tmp_path / "plugins" / "ai-power-tools" / "skills" / "demo"
    (skill / "references").mkdir(parents=True)
    (skill / "SKILL.md").write_text("# Demo\n\n## Real heading\n", encoding="utf-8")
    (skill / "references" / "test-cases.md").write_text(
        "| # | Ask |\n|---|---|\n| TC-01 | one |\n| TC-02 | two |\n", encoding="utf-8")
    (tmp_path / "manifest.json").write_text(json.dumps({"skills": []}), encoding="utf-8")
    model = register.build(tmp_path, {"hand_row": []})
    cell = model.unit("skill:demo").cells["A"]
    assert cell.state == "missing"
    assert cell.text == "cases: 2 · not run"


def test_a_covers_entry_naming_no_unit_is_a_problem(tmp_path):
    (tmp_path / "plugins" / "ai-power-tools" / "skills").mkdir(parents=True)
    (tmp_path / "manifest.json").write_text(json.dumps({"skills": []}), encoding="utf-8")
    (tmp_path / "test_x.py").write_text('COVERS = ("asset:nothing.yaml",)\n', encoding="utf-8")
    model = register.build(tmp_path, {"hand_row": []})
    assert any("asset:nothing.yaml" in p for p in model.problems)


def test_the_results_file_is_read_when_it_exists(tmp_path):
    _demo_skills(tmp_path, {"demo": 20, "other": None})
    results = {"version": "9.9.9", "skills": {"demo": {"passed": 17, "total": 20}}}
    config = {"hand_row": [], "thresholds": {"default": 80}}
    model = register.build(tmp_path, config, results)
    assert model.unit("skill:demo").cells["A"].text == (
        "cases: 20 · last run 9.9.9: 17/20, threshold 80%")
    assert model.unit("skill:other").cells["A"].text == "cases: 0 · not run"
