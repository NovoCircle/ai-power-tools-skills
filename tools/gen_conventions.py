#!/usr/bin/env python3
"""Generate each language's EA `conventions.yaml` from the layout standard.

    python tools/gen_conventions.py           # write every generated file
    python tools/gen_conventions.py --check   # exit 1 if any file differs

The shelf is the master for sizes, spacing, and vocabulary. `layout_map` in each
`ea.yaml` is the master for EA's names. Nobody edits `conventions.yaml`. EA's helper
programs read the generated copy, so nothing crosses packages at run time.

Inputs:
  plugins/ai-power-tools-languages/skills/_languages/layout-standard.yaml
  plugins/ai-power-tools-languages/skills/<id>/language.yaml        its `layout` block
  plugins/ai-power-tools/skills/_shared/languages/ea-translation.yaml
  plugins/ai-power-tools/skills/_shared/languages/<id>/ea.yaml      its `layout_map`

A folder whose `ea.yaml` has no `layout_map` gets no file, so a language can arrive
before its map does. A folder with a `layout_map` and no `language.yaml` is one of EA's
own diagram families, and takes everything from the map. No map anywhere is an error,
because a check over nothing would pass.
"""
from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Mapping
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
SHELF_REL = Path("plugins/ai-power-tools-languages/skills")
EA_REL = Path("plugins/ai-power-tools/skills/_shared/languages")
STANDARD_REL = SHELF_REL / "_languages" / "layout-standard.yaml"
TRANSLATION_REL = EA_REL / "ea-translation.yaml"
GENERATED_NAME = "conventions.yaml"

HEADER = """\
# GENERATED by tools/gen_conventions.py. Do not edit: CI and the plugin build fail on any
# difference. Sizes, spacing, and vocabulary come from the layout standard on the language
# shelf. EA's names come from `layout_map` in this folder's ea.yaml. To change a value,
# change the source and run `python tools/gen_conventions.py`.
"""


class _Dumper(yaml.SafeDumper):
    """Writes a multi-line string as a block, so a note reads the way it was written."""


_Dumper.add_representer(str, lambda dumper, value: dumper.represent_scalar(
    "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None))


class GenerationError(ValueError):
    """A source file can't be translated. The message names the file and the key."""


def _read(path: Path) -> Any:
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except OSError as exc:
        raise GenerationError(f"cannot read {path}: {exc}") from None
    except yaml.YAMLError as exc:
        raise GenerationError(f"{path}: not valid YAML: {exc}") from None


def _lookup(table: Mapping[str, Any], key: Any, where: str, what: str) -> Any:
    if key not in table:
        known = ", ".join(sorted(str(k) for k in table))
        raise GenerationError(f"{where}: {key!r} is not {what}. Known: {known}")
    return table[key]


def _need(table: Mapping[str, Any], key: str, where: str) -> Any:
    """A key the source must state."""
    if key not in table:
        raise GenerationError(f"{where}: missing `{key}`")
    return table[key]


class Sources:
    """The two files every language shares, read once."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.standard = _read(root / STANDARD_REL)
        self.translation = _read(root / TRANSLATION_REL)
        self.factor = self.translation["unit"]["ea_units_per_standard_unit"]

    def scaled(self, value: int) -> int:
        """A standard value in EA units."""
        return value * self.factor

    def size(self, element_type: str, where: str) -> dict[str, int]:
        """`{w, h}` for an element type, in EA units."""
        entry = _lookup(self.standard["element_types"], element_type, where,
                        "an element type in the layout standard")
        if "w" not in entry:
            raise GenerationError(
                f"{where}: {element_type!r} has no box size, so it can't size an element")
        return {"w": self.scaled(entry["w"]), "h": self.scaled(entry["h"])}

    def route(self, name: str, where: str) -> str:
        return _lookup(self.translation["routes"], name, where, "a standard route")

    def grammar(self, name: str, where: str) -> str:
        return _lookup(self.translation["arrangements"], name, where,
                       "a standard arrangement")

    def spacing(self) -> dict[str, int]:
        """Every gap the standard states, under the engine's spec keys."""
        out: dict[str, int] = {}
        for name, targets in self.translation["spacing"].items():
            value = self.standard["spacing"][name]["value"]
            for target in targets:
                out[target["key"]] = self.scaled(value) * target.get("sign", 1)
        container = self.standard["element_types"]["container"]
        for name, targets in self.translation["container"].items():
            for target in targets:
                out[target["key"]] = self.scaled(container[name])
        return out


def _channels(block: Mapping[str, Any] | None) -> dict[str, Any]:
    """The loader's channel block. A diagram type that says nothing claims nothing."""
    block = block or {}
    out: dict[str, Any] = {"fill": block.get("fill")}
    if block.get("claimed"):
        out["claimed"] = dict(block["claimed"])
    if block.get("free"):
        out["free"] = list(block["free"])
    return out


def _size_difference(key: str, element_type: str, layout: Mapping[str, Any],
                     entry: Mapping[str, Any]) -> str | None:
    """Why a size key can't name this size class, or None if it can.

    When a size key is also a concept in the guide's `element_types`, the two must agree,
    or a shape takes one size in EA and another in every other tool. A difference stands
    only if `layout.exceptions` records it for every tool, or the diagram type states
    `size_reason: {<key>: why EA alone differs}`.
    """
    guide_type = (layout.get("element_types") or {}).get(key)
    if guide_type in (None, element_type) or key in (layout.get("exceptions") or {}):
        return None
    reasons = entry.get("size_reason")
    if isinstance(reasons, Mapping) and reasons.get(key):
        return None
    return (f"names {element_type!r}, and the guide's `element_types` says {guide_type!r}. "
            f"Agree with the guide, record it in `layout.exceptions`, or state "
            f"`size_reason: {{{key}: <why>}}` on this diagram type")


def _sizing(sources: Sources, layout: Mapping[str, Any], entry: Mapping[str, Any],
            where: str) -> dict[str, dict[str, int]]:
    """`default`, then the diagram type's size keys, in a stable order.

    A size key is a name EA stores, so only `layout_map` can state one. Each names a guide
    concept or an element type. An element type wins, and no guide concept shares a name
    with one, since concepts are capitalized.
    """
    types = sources.standard["element_types"]
    element_types = layout.get("element_types") or {}
    named: dict[str, dict[str, int]] = {}
    for key, target in (entry.get("size_keys") or {}).items():
        path = f"{where}.size_keys.{key}"
        if target in types:
            element_type = target
        elif target in element_types:
            element_type = element_types[target]
        else:
            raise GenerationError(
                f"{path}: {target!r} is neither an element type nor a concept in this "
                f"language's `layout.element_types`")
        difference = _size_difference(key, element_type, layout, entry)
        if difference:
            raise GenerationError(f"{path}: {difference}")
        named[key] = sources.size(element_type, path)
    out = {"default": sources.size(entry.get("default_type", "box"), f"{where}.default_type")}
    out.update(sorted(named.items()))
    return out


def _diagram_type(sources: Sources, name: str, entry: Mapping[str, Any],
                  layout: Mapping[str, Any], where: str) -> dict[str, Any]:
    """One EA diagram type, from its guide type or, for an EA-only type, from the map."""
    guide = entry.get("guide")
    guide_name = guide[0] if isinstance(guide, list) else guide
    source: Mapping[str, Any]
    if guide_name:
        source = _lookup(layout.get("diagram_types") or {}, guide_name, f"{where}.{name}.guide",
                         "a diagram type in `layout.diagram_types`") or {}
    else:
        source = entry

    defaults = sources.standard["defaults"]
    arrangement = source.get("arrangement") or defaults["arrangement"]
    route = source.get("route") or sources.standard["route_by_arrangement"].get(arrangement)
    if not route:
        raise GenerationError(
            f"{where}.{name}: arrangement {arrangement!r} has no default route, so the "
            f"diagram type must state one")

    routing: dict[str, Any] = {"default": sources.route(route, f"{where}.{name}.route")}
    trunk = source.get("trunk") or {}
    if trunk.get("route"):
        routing["trunk_route"] = sources.route(trunk["route"], f"{where}.{name}.trunk")
    if trunk.get("for"):
        routing["trunk_for"] = list(trunk["for"])

    out: dict[str, Any] = {}
    if entry.get("token"):
        out["token"] = entry["token"]
    if entry.get("base"):
        out["base"] = entry["base"]
    if "stereotype_prefix" in entry:
        out["stereotype_prefix"] = entry["stereotype_prefix"]
    out["grammar"] = sources.grammar(arrangement, f"{where}.{name}.arrangement")
    out["title"] = source.get("title") or defaults["title"]
    out["sizing"] = _sizing(sources, layout, entry, f"{where}.{name}")
    out["spacing"] = sources.spacing()
    out["routing"] = routing
    out["channels"] = _channels(source.get("channels"))
    return out


def _viewpoints(sources: Sources, layout: Mapping[str, Any],
                layout_map: Mapping[str, Any], where: str) -> dict[str, Any]:
    out: dict[str, Any] = {}
    guide_views = layout.get("viewpoints") or {}
    for name, entry in (layout_map.get("viewpoints") or {}).items():
        path = f"{where}.layout_map.viewpoints.{name}"
        row: dict[str, Any] = {"diagram_type": _need(entry, "diagram_type", path)}
        if entry.get("reason") and entry.get("guide") not in guide_views:
            # An exception with a reason. The guide has no viewpoint to read, so EA's name
            # and its diagram type are all there is to say.
            out[name] = row
            continue
        view = _lookup(guide_views, _need(entry, "guide", path), path,
                       "a viewpoint in `layout.viewpoints`")
        if view.get("intent"):
            row["intent"] = list(view["intent"])
        if view.get("admits"):
            row["admits"] = list(view["admits"])
        if view.get("arrangement"):
            row["grammar"] = sources.grammar(view["arrangement"], path)
        if view.get("notes"):
            row["notes"] = view["notes"]
        out[name] = row
    return out


def _profiles(sources: Sources, layout_map: Mapping[str, Any], where: str) -> dict[str, Any] | None:
    """EA's display settings, for a technology that states its own."""
    stated = layout_map.get("presentation_profiles")
    if not stated:
        return None
    out = {name: dict(body)
           for name, body in sources.translation["presentation_profiles"].items()}
    if isinstance(stated, Mapping):
        for name, overrides in stated.items():
            _lookup(out, name, f"{where}.layout_map.presentation_profiles",
                    "a presentation profile in the translation").update(overrides)
    return out


def generate_language(sources: Sources, language_id: str) -> str | None:
    """The text of one `conventions.yaml`, or None if this folder has no `layout_map`."""
    ea_path = sources.root / EA_REL / language_id / "ea.yaml"
    ea = _read(ea_path)
    layout_map = (ea or {}).get("layout_map")
    if not layout_map:
        return None
    where = f"{language_id}"

    language_path = sources.root / SHELF_REL / language_id / "language.yaml"
    layout: Mapping[str, Any] = {}
    if language_path.is_file():
        layout = (_read(language_path) or {}).get("layout")
        if not layout:
            raise GenerationError(
                f"{language_path}: no `layout` block, and {ea_path.name} has a `layout_map`. "
                f"Guides keep the block their stub held.")

    doc: dict[str, Any] = {"technology": _need(layout_map, "technology", f"{ea_path}: layout_map")}
    if layout_map.get("display_name"):
        doc["display_name"] = layout_map["display_name"]
    if layout_map.get("extends"):
        doc["extends"] = layout_map["extends"]
    if "stereotype_prefix" in layout_map:
        doc["stereotype_prefix"] = layout_map["stereotype_prefix"]
    if layout_map.get("notes"):
        doc["notes"] = layout_map["notes"]
    doc["diagram_types"] = {
        name: _diagram_type(sources, name, entry, layout, f"{where}.diagram_types")
        for name, entry in _need(layout_map, "diagram_types", f"{ea_path}: layout_map").items()
    }
    viewpoints = _viewpoints(sources, layout, layout_map, where)
    if viewpoints:
        doc["viewpoints"] = viewpoints
    profiles = _profiles(sources, layout_map, where)
    if profiles:
        doc["presentation_profiles"] = profiles
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100,
                     default_flow_style=False)
    return HEADER + "\n" + body


def _token_of(technology: Any, name: str, entry: Mapping[str, Any]) -> str:
    """The `MDGDgm` token a map entry claims: its own, or `<technology>::<name>`."""
    return entry.get("token") or f"{technology}::{name}"


def _duplicate_tokens(files: Mapping[Path, str]) -> list[str]:
    """Each token that two language folders, or two entries in one, both claim."""
    claims: dict[str, list[str]] = {}
    for path, text in files.items():
        doc = yaml.safe_load(text)
        for name, entry in doc["diagram_types"].items():
            claims.setdefault(_token_of(doc["technology"], name, entry), []).append(path.parent.name)
    return [f"{token!r} is claimed by {', '.join(sorted(folders))}"
            for token, folders in sorted(claims.items()) if len(folders) > 1]


def expected_files(root: Path = ROOT) -> dict[Path, str]:
    """`{path: text}` for every generated file the sources call for.

    Every failure comes back as a `GenerationError`, so the command line and the plugin
    build can both name the source. Most are raised where the key is read. A shape nobody
    guarded still names its language here, in place of a traceback.
    """
    try:
        sources = Sources(root)
    except (KeyError, TypeError, AttributeError) as exc:
        raise GenerationError(f"{STANDARD_REL} or {TRANSLATION_REL} is malformed: {exc!r}") from None
    out: dict[Path, str] = {}
    folders = sorted(p for p in (root / EA_REL).iterdir() if p.is_dir()) if (root / EA_REL).is_dir() else []
    for folder in folders:
        if not (folder / "ea.yaml").is_file():
            continue
        try:
            text = generate_language(sources, folder.name)
        except (KeyError, TypeError, AttributeError) as exc:
            raise GenerationError(f"{folder.name}: a source is malformed: {exc!r}") from None
        if text is not None:
            out[folder / GENERATED_NAME] = text
    if not out:
        raise GenerationError(f"{root / EA_REL}: no `ea.yaml` has a `layout_map`, so there is "
                              f"nothing to generate or check")
    duplicates = _duplicate_tokens(out)
    if duplicates:
        raise GenerationError("one diagram token, more than one claim: " + "; ".join(duplicates))
    return out


def stale_files(root: Path = ROOT) -> list[str]:
    """Generated files that differ from what the sources call for, as repo-relative paths.

    A `conventions.yaml` with no source behind it counts too, so a removed map can't leave
    its numbers behind.
    """
    expected = expected_files(root)
    problems: list[str] = []
    for path, text in expected.items():
        current = path.read_bytes().decode("utf-8") if path.is_file() else None
        if current != text:
            problems.append(path.relative_to(root).as_posix())
    for path in sorted((root / EA_REL).glob(f"*/{GENERATED_NAME}")):
        if path not in expected:
            problems.append(path.relative_to(root).as_posix())
    return problems


# ---------------------------------------------------------------------------
# Checks on the sources. Each returns problems as plain sentences, so a test and the
# language branches can both use them.
# ---------------------------------------------------------------------------
#: A shape in these words needs no `element_types` line: "unlisted" can only mean this.
_BOX_WORDS = re.compile(r"\b(rectangle|rectangles|rectangular|rounded|box|boxes)\b", re.I)
#: A shape that names no drawn symbol, so it has no element type to write down.
_NOT_DRAWN = re.compile(r"^\s*(none|no (symbol|shape)|a line|line of text|text\b|icon\b|marker\b|"
                        r"one line|the keyword|straight line)", re.I)
#: UAF and UPDM say each concept is drawn as the UML element it extends. These bases are
#: not drawn as boxes, so each such concept is written down.
_UML_BASES_NOT_BOX = frozenset({"Comment", "Constraint", "Package", "Interaction", "Port"})


def _names(block: Any) -> set[str]:
    """Names from a guide's `concepts` or `relationships`, in any layout guides use."""
    if isinstance(block, Mapping) and isinstance(block.get("elements"), (Mapping, list)):
        block = block["elements"]
    if isinstance(block, Mapping):
        return {str(key) for key in block}
    if isinstance(block, list):
        return {str(row.get("name")) if isinstance(row, Mapping) else str(row) for row in block}
    return set()


def _stated_none(layout: Mapping[str, Any]) -> set[str]:
    """Concepts a guide says take no element type: `no_element_type` groups, each with a reason."""
    groups = layout.get("no_element_type")
    if not isinstance(groups, Mapping):
        return set()
    return {str(concept) for group in groups.values() if isinstance(group, Mapping)
            and isinstance(group.get("concepts"), list) for concept in group["concepts"]}


def _stated_none_problems(layout: Mapping[str, Any], where: str) -> list[str]:
    """A `no_element_type` block the checks can't read. Its names would clear nothing."""
    groups = layout.get("no_element_type")
    if groups is None:
        return []
    if not isinstance(groups, Mapping):
        return [f"{where}: `no_element_type` must be a mapping of named groups"]
    problems: list[str] = []
    for name, group in groups.items():
        if not isinstance(group, Mapping):
            problems.append(f"{where}: `no_element_type` group `{name}` must be a mapping with "
                            f"a reason and a `concepts` list")
        elif not isinstance(group.get("concepts"), list):
            problems.append(f"{where}: `no_element_type` group `{name}` must list its `concepts` "
                            f"by name, not {group.get('concepts')!r}")
    return problems


def layout_problems(language: Mapping[str, Any], standard: Mapping[str, Any]) -> list[str]:
    """What's wrong with one `language.yaml`'s `layout` block.

    A stub has no concepts to compare against, so its names wait for its guide. Everything
    else is checked on a stub too.
    """
    where = str(language.get("id", "<language>"))
    layout = language.get("layout")
    if not isinstance(layout, Mapping):
        return [f"{where}: no `layout` block"]
    problems: list[str] = []
    vocabulary = standard["vocabulary"]
    types = standard["element_types"]
    element_types = layout.get("element_types") or {}

    for concept, element_type in element_types.items():
        if element_type not in types:
            problems.append(f"{where}: `{concept}` maps to {element_type!r}, which is not an "
                            f"element type in the standard")
    problems.extend(_stated_none_problems(layout, where))
    for name, exception in (layout.get("exceptions") or {}).items():
        if not (isinstance(exception, Mapping) and exception.get("reason") and exception.get("source")):
            problems.append(f"{where}: exception `{name}` needs a reason and a source")
    for name, body in (layout.get("diagram_types") or {}).items():
        if body.get("arrangement") and body["arrangement"] not in vocabulary["arrangements"]:
            problems.append(f"{where}: diagram type `{name}` has arrangement "
                            f"{body['arrangement']!r}, outside the shared vocabulary")
        if body.get("route") and body["route"] not in vocabulary["routes"]:
            problems.append(f"{where}: diagram type `{name}` has route {body['route']!r}, "
                            f"outside the shared vocabulary")
        if body.get("title") and body["title"] not in vocabulary["titles"]:
            problems.append(f"{where}: diagram type `{name}` has title {body['title']!r}, "
                            f"outside the shared vocabulary")
        channels = body.get("channels") or {}
        for channel in [*(channels.get("claimed") or {}), *(channels.get("free") or [])]:
            if channel not in vocabulary["channels"]:
                problems.append(f"{where}: diagram type `{name}` names channel {channel!r}, "
                                f"outside the shared vocabulary")

    if language.get("stub"):
        return problems

    notation = language.get("notation")
    drawn = notation.get("elements") if isinstance(notation, Mapping) else None
    stated_none = _stated_none(layout)
    concepts = _names(language.get("concepts")) | _names(drawn)
    for concept in element_types:
        if concept not in concepts:
            problems.append(f"{where}: `element_types` names `{concept}`, which is not a concept "
                            f"in this guide")
    guide_types = _names(language.get("diagram_types"))
    for name in layout.get("diagram_types") or {}:
        if name not in guide_types:
            problems.append(f"{where}: `layout.diagram_types` names `{name}`, which is not a "
                            f"diagram type in this guide")

    if isinstance(drawn, Mapping):
        for concept, entry in drawn.items():
            shape = entry.get("shape") if isinstance(entry, Mapping) else entry
            if not shape or concept in element_types or concept in stated_none:
                continue
            if _BOX_WORDS.search(str(shape)) or _NOT_DRAWN.search(str(shape)):
                continue
            problems.append(f"{where}: `{concept}` is drawn as {str(shape)[:40]!r}, so it needs an "
                            f"`element_types` line")
    block = language.get("concepts")
    rows = block.get("elements") if isinstance(block, Mapping) and "elements" in block else block
    if isinstance(rows, Mapping):
        for concept, entry in rows.items():
            base = entry.get("uml_base") if isinstance(entry, Mapping) else None
            bases = base if isinstance(base, list) else [base]
            hit = next((b for b in bases if b in _UML_BASES_NOT_BOX), None)
            if hit and concept not in element_types and concept not in stated_none:
                problems.append(f"{where}: `{concept}` is drawn as a UML {hit}, so it needs an "
                                f"`element_types` line")
    return problems


def map_problems(ea: Mapping[str, Any], language: Mapping[str, Any] | None,
                 standard: Mapping[str, Any], grammars: Mapping[str, str]) -> list[str]:
    """What's wrong with one `ea.yaml`'s `layout_map`.

    `grammars` maps `<technology>::<diagram type>` to the grammar the convention files
    recorded on the day they became evidence. A difference needs a one-line
    `arrangement_reason` on that diagram type. Stubs stop before the comparison with the
    rest of `ea.yaml`, which arrives with the language's branch.
    """
    layout_map = ea.get("layout_map") or {}
    where = f"{ea.get('language', '<language>')} layout_map"
    problems: list[str] = []
    technology = layout_map.get("technology")
    layout = (language or {}).get("layout") or {}
    guide_types = layout.get("diagram_types") or {}
    types = standard["element_types"]
    defaults = standard["defaults"]

    for name, entry in (layout_map.get("diagram_types") or {}).items():
        stated = entry.get("token")
        if stated and "::" not in str(stated):
            problems.append(f"{where}: `{name}` has token {stated!r}, which is not a whole token")
        if "::" in name and not stated:
            problems.append(f"{where}: `{name}` holds `::`, so it must state its `token`")
        guide = entry.get("guide")
        first = guide[0] if isinstance(guide, list) else guide
        if first and first not in guide_types:
            problems.append(f"{where}: `{name}` has guide {first!r}, which is not in "
                            f"`layout.diagram_types`")
        source = (guide_types.get(first) or {}) if first else entry
        arrangement = source.get("arrangement") or defaults["arrangement"]
        recorded = grammars.get(_token_of(technology, name, entry))
        if recorded is not None:
            translated = "ea-semantic" if arrangement == "type-fixed" else arrangement
            if translated != recorded and not entry.get("arrangement_reason"):
                problems.append(
                    f"{where}: `{name}` has arrangement {arrangement!r}, and the convention files "
                    f"recorded {recorded!r}. Fix it or add an `arrangement_reason`")
        if entry.get("default_type", "box") not in types:
            problems.append(f"{where}: `{name}` default_type {entry['default_type']!r} is not an "
                            f"element type")
        for key, target in (entry.get("size_keys") or {}).items():
            element_type = target if target in types else (layout.get("element_types") or {}).get(target)
            difference = _size_difference(key, element_type, layout, entry) if element_type else None
            if difference:
                problems.append(f"{where}: `{name}` size key `{key}` {difference}")

    views = layout.get("viewpoints") or {}
    for name, entry in (layout_map.get("viewpoints") or {}).items():
        if entry.get("guide") not in views and not entry.get("reason"):
            problems.append(f"{where}: viewpoint `{name}` names {entry.get('guide')!r}, which is "
                            f"not in `layout.viewpoints`")

    if ea.get("stub") or (language or {}).get("stub"):
        return problems

    # The whole ea.yaml is here, so the map must agree with it.
    if (technology and ea.get("technology") not in (None, "none", technology)
            and ea.get("api_technology_id") != technology
            and not layout_map.get("technology_reason")):
        problems.append(f"{where}: technology {technology!r} differs from ea.yaml's "
                        f"{ea.get('technology')!r}")
    if language:
        concepts = _names(language.get("concepts"))
        for name, view in views.items():
            for concept in view.get("admits") or ():
                if concept not in concepts:
                    problems.append(f"{ea.get('language')}: viewpoint `{name}` admits `{concept}`, "
                                    f"which is not a concept in this guide")
    declared = ea.get("diagram_types") or {}
    tokens = {str(row.get(key)) for row in declared.values() if isinstance(row, Mapping)
              for key in ("token", "ea_name")} if isinstance(declared, Mapping) else set()
    for name, entry in (layout_map.get("diagram_types") or {}).items():
        token = _token_of(technology, name, entry)
        known = token in tokens or (not entry.get("token") and name in tokens)
        if tokens and not known and not entry.get("token_reason"):
            problems.append(f"{where}: `{token}` is not in ea.yaml's `diagram_types`")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a generated file differs, and write nothing")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    try:
        if args.check:
            stale = stale_files(args.root)
            for rel in stale:
                print(f"stale: {rel}", file=sys.stderr)
            if stale:
                print("Run `python tools/gen_conventions.py` and commit the result.",
                      file=sys.stderr)
                return 1
            print(f"{len(expected_files(args.root))} generated files match their sources.")
            return 0
        expected = expected_files(args.root)
        for path, text in expected.items():
            path.write_bytes(text.encode("utf-8"))
        for path in sorted((args.root / EA_REL).glob(f"*/{GENERATED_NAME}")):
            if path not in expected:
                path.unlink()
        print(f"Wrote {len(expected)} generated files.")
        return 0
    except GenerationError as exc:
        print(f"gen_conventions: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
